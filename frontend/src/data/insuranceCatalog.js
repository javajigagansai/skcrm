/**
 * Returns predefined policy names for a given insurance company and category.
 * If exact match isn't found, returns all policies for that company, or category fallbacks.
 */
export const getPredefinedPolicies = (companyName, categoryName) => {
  if (!companyName) return [];

  // Normalize company name match
  const compKey = Object.keys(INSURANCE_PRODUCTS_CATALOG).find(
    k => k.toLowerCase().trim() === companyName.toLowerCase().trim() ||
         k.toLowerCase().includes(companyName.toLowerCase().trim()) ||
         companyName.toLowerCase().includes(k.toLowerCase().trim())
  );

  if (!compKey) {
    // Return generic category recommendations
    return getGenericCategoryPolicies(categoryName);
  }

  const compData = INSURANCE_PRODUCTS_CATALOG[compKey] || {};

  if (categoryName && categoryName !== 'ALL' && categoryName !== 'CUSTOM') {
    // Look for exact or fuzzy category match
    const catKey = Object.keys(compData).find(
      c => c.toLowerCase().trim() === categoryName.toLowerCase().trim() ||
           c.toLowerCase().includes(categoryName.toLowerCase().trim()) ||
           categoryName.toLowerCase().includes(c.toLowerCase().trim())
    );

    if (catKey && compData[catKey]) {
      return compData[catKey];
    }
  }

  // If category wasn't specified, aggregate all policies for this company
  const allForComp = [];
  Object.values(compData).forEach(arr => {
    if (Array.isArray(arr)) allForComp.push(...arr);
  });

  return allForComp.length > 0 ? allForComp : getGenericCategoryPolicies(categoryName);
};

const getGenericCategoryPolicies = (categoryName) => {
  if (!categoryName) return [];
  const catLower = categoryName.toLowerCase();
  if (catLower.includes('health')) {
    return [
      'Comprehensive Family Health Floater',
      'Super Top-Up Health Shield',
      'Senior Citizen Critical Health Cover',
      'Arogya Sanjeevani Standard Policy',
      'OPD + Cashless Mediclaim Plan'
    ];
  }
  if (catLower.includes('life') || catLower.includes('term')) {
    return [
      'Pure Term Life Cover with Critical Illness',
      'Term Plan with Return of Premium (ROP)',
      'Guaranteed Wealth & Income Life Plan',
      'Saral Jeevan Bima Standard Term'
    ];
  }
  if (catLower.includes('motor') || catLower.includes('car') || catLower.includes('vehicle')) {
    return [
      'Comprehensive Bumper-to-Bumper Zero Dep Policy',
      'Standalone Own Damage (OD) Motor Cover',
      'Third Party Only Statutory Liability Cover',
      'Pay As You Drive Motor Plan'
    ];
  }
  if (catLower.includes('travel')) {
    return [
      'Worldwide Multi-Trip International Travel Shield',
      'Single Trip Overseas Medical & Travel Plan',
      'Student International Travel Insurance'
    ];
  }
  if (catLower.includes('fire') || catLower.includes('commercial')) {
    return [
      'Bharat Sookshma Udyam Suraksha',
      'Bharat Griha Raksha Property Protection',
      'Standard Fire and Special Perils Cover'
    ];
  }
  return [
    'Standard Comprehensive Protection Plan',
    'Executive Platinum Shield Plan',
    'Customized Tailored Insurance Solution'
  ];
};
